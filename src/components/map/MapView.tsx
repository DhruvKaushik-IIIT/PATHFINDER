"use client";

// Full-screen base map (CLAUDE.md 7.6): MapLibre + OpenFreeMap tiles restyled to Glass,
// faint dashed HP boundary, our road-segment layer, and the my-location dot.
import "maplibre-gl/dist/maplibre-gl.css";
import type { FeatureCollection } from "geojson";
import { setWorkerUrl, type StyleSpecification } from "maplibre-gl";
import { useEffect, useState, type Ref } from "react";
import Map, { AttributionControl, Layer, Marker, Source, type MapRef } from "react-map-gl/maplibre";
import type { MapEvent } from "@/lib/events/types";
import EventPin from "./EventPin";
import { loadGlassStyle } from "./glassStyle";

// MapLibre 6 loads its worker from next to its own bundle, which Next.js doesn't emit.
// predev/prebuild copy it into public/vendor/ (same installed version).
setWorkerUrl("/vendor/maplibre-gl-worker.mjs");

export const MANDI = { latitude: 31.708, longitude: 76.932 };
// Pan freely across North India so routes from Delhi / Punjab / J&K stay visible (7.6).
const NORTH_INDIA: [number, number, number, number] = [72, 26, 82, 35]; // W, S, E, N

async function loadGeo(path: string): Promise<FeatureCollection | null> {
  try {
    const res = await fetch(path);
    return res.ok ? ((await res.json()) as FeatureCollection) : null;
  } catch {
    return null;
  }
}

export interface LatLng {
  latitude: number;
  longitude: number;
}

export default function MapView({
  mapRef,
  myLocation,
  showRoadLayer = true,
  events = [],
  selectedEventId = null,
  onSelectEvent,
  onViewChange,
  initialView,
  children,
}: {
  mapRef?: Ref<MapRef>;
  myLocation?: LatLng | null;
  showRoadLayer?: boolean;
  events?: MapEvent[];
  selectedEventId?: string | null;
  onSelectEvent?: (e: MapEvent) => void;
  /** Fires after load and after each pan/zoom (e.g. to refetch events for the new area). */
  onViewChange?: () => void;
  initialView?: LatLng & { zoom: number };
  children?: React.ReactNode;
}) {
  const [style, setStyle] = useState<StyleSpecification | null>(null);
  const [styleFailed, setStyleFailed] = useState(false);
  const [boundary, setBoundary] = useState<FeatureCollection | null>(null);
  const [roads, setRoads] = useState<FeatureCollection | null>(null);

  useEffect(() => {
    loadGlassStyle().then(setStyle, () => setStyleFailed(true));
    // Generated by scripts/fetch-roads.ts; absent until it has run → layers simply don't show.
    loadGeo("/geo/hp-boundary.geojson").then(setBoundary);
    loadGeo("/geo/corridor.geojson").then(setRoads);
  }, []);

  if (!style) {
    return (
      <div className="absolute inset-0 bg-land" aria-label="Map loading">
        {styleFailed && (
          <p className="absolute left-1/2 top-24 -translate-x-1/2 text-sm text-ink-3">Map tiles unavailable right now</p>
        )}
      </div>
    );
  }

  return (
    <Map
      ref={mapRef}
      mapStyle={style}
      initialViewState={initialView ?? { ...MANDI, zoom: 9 }}
      maxBounds={NORTH_INDIA}
      minZoom={5}
      style={{ position: "absolute", inset: 0 }}
      attributionControl={false}
      dragRotate={false}
      pitchWithRotate={false}
      touchPitch={false}
      onLoad={(e) => {
        // Compact attribution starts expanded; start collapsed to the (i) button.
        e.target.getContainer().querySelector(".maplibregl-ctrl-attrib")?.classList.remove("maplibregl-compact-show");
        onViewChange?.();
      }}
      onMoveEnd={() => onViewChange?.()}
    >
      {/* Top-left, under the profile button: the sheet covers the bottom of the map. */}
      <AttributionControl position="top-left" compact customAttribution="© OpenStreetMap contributors · OpenFreeMap" />

      {boundary && (
        <Source id="hp-boundary" type="geojson" data={boundary}>
          <Layer
            id="hp-boundary-line"
            type="line"
            paint={{ "line-color": "#6E6E73", "line-width": 1.2, "line-opacity": 0.45, "line-dasharray": [3, 2] }}
          />
        </Source>
      )}

      {roads && (
        <Source id="pf-roads" type="geojson" data={roads}>
          <Layer
            id="pf-roads-line"
            type="line"
            layout={{ visibility: showRoadLayer ? "visible" : "none", "line-cap": "round", "line-join": "round" }}
            paint={{
              "line-color": "#0071E3",
              "line-opacity": 0.28,
              "line-width": ["interpolate", ["linear"], ["zoom"], 7, 1.5, 12, 4],
            }}
          />
        </Source>
      )}

      {events.map((ev) => (
        <Marker key={ev.id} latitude={ev.lat} longitude={ev.lng} anchor="center" style={{ zIndex: ev.id === selectedEventId ? 2 : 1 }}>
          <EventPin event={ev} selected={ev.id === selectedEventId} onClick={() => onSelectEvent?.(ev)} />
        </Marker>
      ))}

      {children}

      {myLocation && (
        <Marker latitude={myLocation.latitude} longitude={myLocation.longitude} anchor="center">
          <span
            aria-label="Your location"
            className="block size-4 rounded-full border-[3px] border-white bg-me"
            style={{ boxShadow: "0 0 0 7px rgba(10,132,255,0.18)" }}
          />
        </Marker>
      )}
    </Map>
  );
}
